//! Generate a Swift JSON-RPC client from [`crate::CONTROL_SCHEMA`].

use crate::{API_VERSION, EVENT_KINDS, METHODS};

/// Swift source generated from the schema/method tables.
#[tracing::instrument(level = "debug", target = "ternvale::api", skip_all)]
pub fn generate_swift_client() -> String {
    let mut methods = String::new();
    for method in METHODS {
        let case = swift_ident(method.as_str());
        methods.push_str(&format!("    case {case} = \"{}\"\n", method.as_str()));
    }
    let mut events = String::new();
    for kind in EVENT_KINDS {
        let case = swift_ident(kind.as_str());
        events.push_str(&format!("    case {case} = \"{}\"\n", kind.as_str()));
    }
    format!(
        r#"// Generated from ternvale-api (docs/schema/control-api.json). Do not edit.
// Regenerated by `cargo test -p ternvale-api --test golden` (writes this file).
import Foundation

/// Control API version this client was generated for.
public let ternvaleApiVersion: UInt32 = {API_VERSION}

/// JSON-RPC 2.0 method names. Existing cases are frozen.
public enum TernvaleMethod: String, Codable, CaseIterable {{
{methods}}}

/// Event kinds from `subscribe`.
public enum TernvaleEventKind: String, Codable, CaseIterable {{
{events}}}

/// JSON-RPC 2.0 request (one object per line on the Unix socket).
public struct TernvaleJsonRpcRequest: Codable {{
    public var jsonrpc: String = "2.0"
    public var method: String
    public var params: [String: AnyCodable]?
    public var id: AnyCodable?

    public init(method: TernvaleMethod, params: [String: AnyCodable]? = nil, id: Int) {{
        self.method = method.rawValue
        self.params = params
        self.id = AnyCodable(id)
    }}
}}

/// JSON-RPC 2.0 response.
public struct TernvaleJsonRpcResponse: Codable {{
    public var jsonrpc: String
    public var result: AnyCodable?
    public var error: TernvaleJsonRpcError?
    public var id: AnyCodable
}}

public struct TernvaleJsonRpcError: Codable {{
    public var code: Int
    public var message: String
}}

/// Handshake params (`api_version`).
public struct TernvaleHandshakeParams: Codable {{
    public var api_version: UInt32
    public init(apiVersion: UInt32 = ternvaleApiVersion) {{
        self.api_version = apiVersion
    }}
}}

/// Minimal type-erased JSON value for generated Codable envelopes.
public struct AnyCodable: Codable {{
    public let value: Any
    public init(_ value: Any) {{ self.value = value }}
    public init(from decoder: Decoder) throws {{
        let container = try decoder.singleValueContainer()
        if let v = try? container.decode(Bool.self) {{ value = v; return }}
        if let v = try? container.decode(Int.self) {{ value = v; return }}
        if let v = try? container.decode(UInt64.self) {{ value = v; return }}
        if let v = try? container.decode(Double.self) {{ value = v; return }}
        if let v = try? container.decode(String.self) {{ value = v; return }}
        value = NSNull()
    }}
    public func encode(to encoder: Encoder) throws {{
        var container = encoder.singleValueContainer()
        switch value {{
        case let v as Bool: try container.encode(v)
        case let v as Int: try container.encode(v)
        case let v as UInt64: try container.encode(v)
        case let v as Double: try container.encode(v)
        case let v as String: try container.encode(v)
        default: try container.encodeNil()
        }}
    }}
}}

/// Async Unix-socket JSON-RPC client (connects to `api.sock` or a per-VM socket).
public final class TernvaleControlClient {{
    private let path: String
    private var nextId: Int = 1

    public init(socketPath: String) {{
        self.path = socketPath
    }}

    public func handshake() async throws -> TernvaleJsonRpcResponse {{
        try await call(.handshake, params: ["api_version": AnyCodable(Int(ternvaleApiVersion))])
    }}

    public func call(_ method: TernvaleMethod, params: [String: AnyCodable]? = nil) async throws -> TernvaleJsonRpcResponse {{
        let id = nextId
        nextId += 1
        let request = TernvaleJsonRpcRequest(method: method, params: params, id: id)
        let data = try JSONEncoder().encode(request)
        var line = data
        line.append(0x0A)
        let fd = Darwin.socket(AF_UNIX, SOCK_STREAM, 0)
        if fd < 0 {{ throw POSIXError(.init(rawValue: errno) ?? .EIO) }}
        defer {{ Darwin.close(fd) }}
        try connectUnix(fd: fd, path: path)
        let sent = line.withUnsafeBytes {{ ptr in Darwin.write(fd, ptr.baseAddress, ptr.count) }}
        if sent < 0 {{ throw POSIXError(.init(rawValue: errno) ?? .EIO) }}
        var buffer = Data()
        var chunk = [UInt8](repeating: 0, count: 4096)
        while true {{
            let n = Darwin.read(fd, &chunk, chunk.count)
            if n <= 0 {{ break }}
            buffer.append(chunk, count: n)
            if buffer.contains(0x0A) {{ break }}
        }}
        guard let newline = buffer.firstIndex(of: 0x0A) else {{
            throw POSIXError(.EIO)
        }}
        return try JSONDecoder().decode(TernvaleJsonRpcResponse.self, from: buffer[..<newline])
    }}

    private func connectUnix(fd: Int32, path: String) throws {{
        var addr = sockaddr_un()
        addr.sun_family = sa_family_t(AF_UNIX)
        let bytes = Array(path.utf8)
        if bytes.count >= MemoryLayout.size(ofValue: addr.sun_path) {{
            throw POSIXError(.ENAMETOOLONG)
        }}
        withUnsafeMutableBytes(of: &addr.sun_path) {{ raw in
            for (i, b) in bytes.enumerated() {{ raw[i] = b }}
        }}
        let size = socklen_t(MemoryLayout<sockaddr_un>.size)
        let rc = withUnsafePointer(to: &addr) {{ ptr in
            ptr.withMemoryRebound(to: sockaddr.self, capacity: 1) {{ Darwin.connect(fd, $0, size) }}
        }}
        if rc != 0 {{ throw POSIXError(.init(rawValue: errno) ?? .EIO) }}
    }}
}}
"#,
        methods = methods,
        events = events,
        API_VERSION = API_VERSION,
    )
}

fn swift_ident(wire: &str) -> String {
    let mut out = String::new();
    let mut cap = false;
    for (i, ch) in wire.chars().enumerate() {
        if ch == '.' || ch == '-' {
            cap = true;
            continue;
        }
        if i == 0 {
            out.push(ch);
        } else if cap {
            out.extend(ch.to_uppercase());
            cap = false;
        } else {
            out.push(ch);
        }
    }
    out
}

