#!/usr/bin/env python3
"""Write THIRD_PARTY_NOTICES.md from `cargo deny list` plus bundled components."""
from __future__ import annotations

import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "THIRD_PARTY_NOTICES.md"

BUNDLED = """
## Optional / not linked into Ternvale.app

These are **not** compiled into the VMM. Some are fetched by helper scripts for
guest installers. Review upstream terms before you redistribute them yourself.

| Component | When present | License | GPL/LGPL? | Shipped in Ternvale.app? |
| --- | --- | --- | --- | --- |
| Sparkle 2 | Swift app SPM | MIT | no | Yes (dynamic framework), if the Mac app is built |
| EDK2 / AAVMF (`QEMU_EFI.fd`) | `scripts/fetch-firmware.sh` | BSD-2-Clause-Patent (TianoCore) | no | No (user fetch into `test-assets/firmware`) |
| swtpm | `brew install swtpm` | BSD-3-Clause | no | No (host tool) |
| virtio-win ISO | `scripts/fetch-virtio-win.sh` | BSD-3-Clause (kvm-guest-drivers-windows) | no | No |
| WinFsp MSI | `scripts/fetch-winfsp.sh` | **GPLv3 + FLOSS exception** | **GPL** (exception for unmodified MSI + FLOSS host) | **No** |
| virglrenderer / rutabaga_gfx | not linked (`gpu3d` is a local command surface) | BSD-3-Clause upstream; not vendored | no | No |

### WinFsp (GPL) — shipping rule

Ternvale **must not** statically or dynamically link `winfsp-*.dll` into the
Mac app or the VMM. The unmodified official MSI may be placed on a tools ISO
for Windows guests because Ternvale is FLOSS (MIT OR Apache-2.0) and credits
WinFsp; see `docs/LICENSES.md`. Closed-source forks cannot ship that MSI
under the FLOSS exception.

### Sparkle

https://github.com/sparkle-project/Sparkle — MIT. EdDSA appcast verification
is in addition to Developer ID notarization.

### EDK2

Firmware used for UEFI guests is the Alpine `aavmf` ArmVirtQemu build (EDK2).
Ternvale does not compile EDK2 in this tree.

### GPU

No Mesa, virglrenderer, or MoltenVK binary is redistributed. The optional
`gpu3d` module is Ternvale source (MIT OR Apache-2.0) with comments pointing
at crosvm `rutabaga_gfx` (BSD-3-Clause) for a future optional link.
"""


def main() -> int:
    proc = subprocess.run(
        ["cargo", "deny", "list"],
        cwd=ROOT,
        capture_output=True,
        text=True,
    )
    if proc.returncode != 0:
        sys.stderr.write(proc.stderr)
        return proc.returncode
    lines = []
    for raw in proc.stdout.splitlines():
        if raw.startswith("Unlicensed"):
            continue
        lines.append(raw)
    body = "\n".join(lines)
    text = f"""# Third-party notices

Generated by `python3 scripts/licenses/generate-notices.py`.
Re-run after dependency changes. Policy: `deny.toml` (`cargo deny check licenses`).

Ternvale itself: **MIT OR Apache-2.0** (`LICENSE`, `LICENSE-MIT`).

## Cargo crates (`aarch64-apple-darwin`)

No crate in this graph is GPL or LGPL. Allowed OSI licenses: MIT, Apache-2.0,
BSD-2-Clause, BSD-3-Clause, ISC, Unicode-3.0, Unlicense, Zlib.

```
{body}
```

{BUNDLED}
"""
    OUT.write_text(text, encoding="utf-8")
    print(OUT)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
