/* Modern virtio-pci BAR0 layout (virtio 1.2 §4.1.4) as Ternvale implements it.
 * The driver still parses vendor capabilities; these offsets match
 * ternvale-devices virtio/pci/caps.rs when the host is Ternvale.
 */
#pragma once

#define VIRTIO_PCI_CAP_COMMON 1
#define VIRTIO_PCI_CAP_NOTIFY 2
#define VIRTIO_PCI_CAP_ISR 3
#define VIRTIO_PCI_CAP_DEVICE 4
#define VIRTIO_PCI_CAP_PCI_CFG 5

#define VIRTIO_PCI_COMMON_OFFSET 0x0000u
#define VIRTIO_PCI_ISR_OFFSET 0x1000u
#define VIRTIO_PCI_DEVICE_OFFSET 0x2000u
#define VIRTIO_PCI_NOTIFY_OFFSET 0x3000u
#define VIRTIO_PCI_REGION_SIZE 0x1000u
#define VIRTIO_PCI_NOTIFY_MULTIPLIER 4u

#define VIRTIO_PCI_COMMON_DFSELECT 0x00u
#define VIRTIO_PCI_COMMON_DFEATURE 0x04u
#define VIRTIO_PCI_COMMON_GFSELECT 0x08u
#define VIRTIO_PCI_COMMON_GFEATURE 0x0Cu
#define VIRTIO_PCI_COMMON_MSIX 0x10u
#define VIRTIO_PCI_COMMON_NUMQ 0x12u
#define VIRTIO_PCI_COMMON_STATUS 0x14u
#define VIRTIO_PCI_COMMON_GEN 0x15u
#define VIRTIO_PCI_COMMON_QSELECT 0x16u
#define VIRTIO_PCI_COMMON_QSIZE 0x18u
#define VIRTIO_PCI_COMMON_QMSIX 0x1Au
#define VIRTIO_PCI_COMMON_QENABLE 0x1Cu
#define VIRTIO_PCI_COMMON_QNOTIFY 0x1Eu
#define VIRTIO_PCI_COMMON_QDESC 0x20u
#define VIRTIO_PCI_COMMON_QDRIVER 0x28u
#define VIRTIO_PCI_COMMON_QDEVICE 0x30u

#define VIRTIO_S_ACKNOWLEDGE 1u
#define VIRTIO_S_DRIVER 2u
#define VIRTIO_S_DRIVER_OK 4u
#define VIRTIO_S_FEATURES_OK 8u
#define VIRTIO_S_FAILED 128u

#define VIRTIO_F_VERSION_1 (1ull << 32)
#define VIRTIO_F_ACCESS_PLATFORM (1ull << 33)

#define VRING_DESC_F_NEXT 1u
#define VRING_DESC_F_WRITE 2u

#define VIRTIO_ISR_QUEUE 1u
#define VIRTIO_ISR_CONFIG 2u

#define TVGPU_QUEUE_CONTROL 0u
#define TVGPU_QUEUE_CURSOR 1u
#define TVGPU_QUEUE_SIZE 64u
#define TVGPU_MAX_DIMENSION 16384u
